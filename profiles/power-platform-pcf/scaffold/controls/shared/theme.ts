/**
 * The theme a control renders with. The rule:
 *
 * - Inside Power Apps, follow the app. Model-driven apps with the modern look and canvas apps with
 *   modern themes pass Fluent v9 tokens in context.fluentDesignLanguage.tokenTheme; the control
 *   renders with them, so it is light or dark (and follows display density) exactly as the app
 *   around it. A model-driven app carries the brand through its own theme (the solution's
 *   dataverse-theme.xml, from the same design system), so the control matches without branding
 *   itself.
 * - Everywhere else, the design system: hosts without modern theming (classic forms, the test
 *   harness, canvas apps without modern themes, a standalone page) get the project's design
 *   system (shared/design-system/fluent-theme.ts, generated by the build framework's
 *   scripts/design-system.mjs), dark when the host says dark.
 * - A control that must carry the brand even inside an app (a branded canvas component) asks for
 *   it: hostTheme(context, { carryBrand: true }).
 *
 * Read it in every updateView: the theme can change while the control is on screen. Colours
 * outside Fluent controls come from shared/design-system/tokens.ts (role(), color()), never as
 * literals.
 */
import type { Theme } from "@fluentui/react-components";
import { darkTheme, lightTheme } from "./design-system/fluent-theme";

export interface ThemeOptions {
  /** Use the design system even when the host passes its own theme. */
  carryBrand?: boolean;
}

export function hostTheme(context: ComponentFramework.Context<unknown>, options: ThemeOptions = {}): Theme {
  const design = context.fluentDesignLanguage;
  if (design?.tokenTheme && !options.carryBrand) return design.tokenTheme as unknown as Theme;
  return design?.isDarkTheme ? darkTheme : lightTheme;
}

/** Text direction for the reader's language (Arabic and Hebrew are right to left). */
export function hostDirection(context: ComponentFramework.Context<unknown>): "ltr" | "rtl" {
  return context.userSettings.isRTL ? "rtl" : "ltr";
}
